"""Packages the robot face so it runs on the panel with NO PC or network.

  python make_standalone.py

Writes ./standalone/ with index.html, reminders.js (from reminders.json) and the sounds folder.
Copy that folder to the panel's microSD card and open its index.html in the panel's browser.
"""
import json
import os
import shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "standalone")

if os.path.isdir(OUT):
    shutil.rmtree(OUT)
os.makedirs(OUT)

shutil.copy(os.path.join(ROOT, "face.html"), os.path.join(OUT, "index.html"))
shutil.copy(os.path.join(ROOT, "weather.js"), os.path.join(OUT, "weather.js"))
shutil.copytree(os.path.join(ROOT, "sounds"), os.path.join(OUT, "sounds"))

with open(os.path.join(ROOT, "reminders.json"), encoding="utf-8") as f:
    reminders = json.load(f)
with open(os.path.join(OUT, "reminders.js"), "w", encoding="utf-8") as f:
    f.write("// generated by make_standalone.py from reminders.json\nvar REMINDERS = %s;\n" % json.dumps(reminders, indent=2))

total = sum(os.path.getsize(os.path.join(d, n)) for d, _, ns in os.walk(OUT) for n in ns)
print("wrote %s (%d KB)" % (OUT, total // 1024))
